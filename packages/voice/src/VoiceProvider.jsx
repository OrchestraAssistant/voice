// A friendly name for each built-in provider, used in the engine picker when
// the host passes a bare provider rather than a { label, provider } entry.
const PROVIDER_LABELS = {
  orchestra: "Orchestra",
  "openai-realtime": "OpenAI Realtime",
};

/**
 * Performs the request and hands the whole outcome back, status included.
 *
 * Deliberately does NOT throw on a non-2xx. tRPC answers errors with a
 * structured body and an HTTP status, and the useful half is the body: failing
 * here reported "Request failed: 401" and discarded the message that said why.
 * Which reply counts as a failure is the transport's question.
 */
async function apiFetch(method, url, body) {
  const res = await fetch(url, {
    method,
    headers: body ? { "Content-Type": "application/json" } : undefined,
    body: body ? JSON.stringify(body) : undefined,
  });
  const text = await res.text();
  let data = null;
  try {
    data = text ? JSON.parse(text) : null;
  } catch {
    // An HTML error page, most often. The status is what carries meaning then.
    data = null;
  }
  return { ok: res.ok, status: res.status, data };
}

/**
 * VoiceProvider mounts the interpreter for the app it wraps. Everything it
 * exposes is reachable through the `useInterpreter()` hook, so a consumer
 * never has to touch this component directly to build a custom UI.
 *
 * Optional callback props are the escape hatch for side effects that
 * aren't about rendering at all -- analytics, toasts, syncing an external
 * store -- fired at the same points the internal state updates, so they
 * never depend on any UI actually being mounted:
 *
 *   onToolCall(name, args, result)  -- fires after every tool call the
 *     model makes resolves, whatever kind it is (query/action/DOM/nav).
 *   onTranscript({ role, text })    -- fires for every completed turn.
 *   onPendingAction(action | null)  -- fires when a destructive action is
 *     staged for confirmation, and again with null when it's resolved.
 *   onModeChange(mode)              -- fires on continuous/ptt/ptnt switch.
 *   onTransportChange(transport)    -- fires on connection state change. Not the
 *     same as "the mic is live"; see isListening().
 *   onHangUp({ because })           -- fires when the model ends the
 *     conversation because the user dismissed it, carrying the words that
 *     did it. The widget has already released the microphone by then.
 *
 * Two host integration points, both optional, both injected rather than
 * imported. The widget deliberately does not depend on react-router or
 * react-query -- a host app may use neither, and a package that imports
 * them would force both on everyone who installs it:
 *
 *   relayUrl           -- origin of the voice relay ("" = same origin, the
 *     default, which suits a dev proxy; set it to your hosted relay in
 *     production since the host app won't be on the same domain).
 *   navigate(path)     -- how this app changes route. Defaults to a plain
 *     history.pushState + popstate, which works anywhere but won't
 *     re-render a router that isn't listening for it; pass your router's
 *     navigate (e.g. react-router's useNavigate()) for a real SPA nav.
 *   onAfterAction({ name, count, result })  -- called once after a write
 *     operation lands, so the host can refresh whatever cache it keeps
 *     (`() => queryClient.invalidateQueries()`), optionally surgically via the
 *     action `name`. Without it, we synthesise a focus event, which most
 *     React-Query/SWR apps refetch on -- so the UI updates even unwired.
 *   manifest           -- REQUIRED. Your app's own .voice/manifest.json,
 *     imported and passed in. It is an artifact of your source: generated by
 *     `npx @expert/voice-cli`, committed beside your code, bundled with it.
 *     So it cannot describe a different version of the app than the one
 *     running. The widget executes tool calls against it AND sends it to the
 *     relay, which builds the model's tool list from it -- one object, rather
 *     than two copies that agree by convention until one of them moves.
 */
export function VoiceProvider({
  children,
  manifest,
  /**
   * The voice-to-action pipeline(s) this app offers. Each is a provider object
   * -- { id, capabilities, connect } (see PROVIDERS.md) -- or a { label, provider }
   * pair to name it in the engine picker. The host passes the providers it has
   * actually wired, because each needs its own server half (the relay for
   * OpenAI Realtime, whatever another realtime API needs); the user then picks among
   * them in Settings, the same way they pick a model.
   *
   * Omitted, it defaults to Orchestra, the hosted provider, whose token route
   * is `${relayUrl}/voice/token` on the app's own server. OpenAI Realtime is
   * `provider={openaiRealtime()}`, with its relay at `relayUrl`.
   * Pass a stable array (define it outside render or memoise it); a fresh array
   * each render re-validates the providers and is wasted work.
   */
  providers,
  /**
   * A single provider -- the ergonomic form of a one-entry `providers`. Ignored
   * when `providers` is given. `provider={orchestra()}` and the default are
   * the same thing written two ways.
   */
  provider,
  relayUrl = "",
  navigate: navigateProp,
  onAfterAction,
  onToolCall,
  onTranscript,
  onPendingAction,
  onModeChange,
  onTransportChange,
  onHangUp,
  logToRelay = false,
  /**
   * How long a hung-up session is held before the connection is closed too.
   *
   * Hanging up releases the microphone immediately -- that is the part the
   * user asked for and can verify from the OS indicator. Closing the
   * connection is a separate, later decision, because prompt caching is
   * session-scoped: a session closed and reopened pays the whole instruction
   * prefix again, and someone who says "actually, one more thing" ten seconds
   * later should not pay for having been polite.
   */
  idleCloseMs = 5 * 60_000,
  /**
   * How much of the connect to do before the user asks to talk.
   *
   *   "off"    nothing until the Talk button. ~1.6s of dead air on the click.
   *   "open"   mint AND connect when the panel opens; only the microphone is
   *            left for the click.
   *   "eager"  mint on mount and keep a fresh key; connect when the panel
   *            opens. Same click as "open", but the panel-open connect is
   *            shorter by the whole mint.
   *   "hover"  mint on mount; connect when the pointer reaches the pill, which
   *            is earlier than the click that opens it. Costs a connect for
   *            anyone whose cursor merely crosses that corner of the screen.
   *
   * The microphone is never taken early in any of them. You could, silently,
   * for users who have already granted permission -- and it lights the OS
   * recording indicator, which is how a widget gets distrusted.
   */
  warmup = "hover",
}) {
  // What the relay is willing to offer. Fetched rather than hard-coded so the
  // list of models stays a server-side decision.
  const [options, setOptions] = useState({ models: [], languages: [], defaults: {} });
  const [model, setModelState] = useState(null); // null = the relay's default
  const [language, setLanguageState] = useState("auto");

  // The providers on offer, normalised to { id, label, provider, capabilities }.
  // Defaults to the one realtime provider when the host passes none, so a plain
  // <VoiceProvider relayUrl=...> behaves exactly as before.
  const providerList = useMemo(() => {
    const raw =
      providers && providers.length ? providers : provider ? [provider] : [orchestra({ tokenUrl: `${relayUrl}/voice/token` })];
    return raw.map((entry) => {
      const p = entry && typeof entry.connect === "function" ? entry : entry?.provider;
      validateProvider(p); // throws at mount on a factory passed uncalled, etc.
      return {
        id: p.id,
        label: entry.label ?? PROVIDER_LABELS[p.id] ?? p.id,
        provider: p,
        capabilities: p.capabilities,
      };
    });
  }, [providers, provider, relayUrl]);
  // Which one is live. null means "the first offered", so the default needs no
  // initial value that could disagree with the list.
  const [providerId, setProviderIdState] = useState(null);
  const activeProvider = providerList.find((p) => p.id === providerId) ?? providerList[0];
  const capabilities = activeProvider.capabilities;
  // Read through a ref inside connect/warm so a switch takes effect on the next
  // connect without those callbacks having to list it as a dependency -- the
  // same reason model/language reconnects thread an `overrides` object.
  const activeProviderRef = useRef(activeProvider);
  activeProviderRef.current = activeProvider;

  // The neutral tool list a non-realtime provider consumes (the realtime one
  // builds its own on the relay and ignores this). Recomputed only when the
  // manifest changes.
  const catalog = useMemo(() => toolCatalog(manifest ?? {}), [manifest]);
  // Purely a display preference, so unlike model and language it changes
  // instantly and never touches the session.
  const [rimMode, setRimMode] = useState("state");
  // TRANSPORT only: is the realtime connection up. Deliberately says nothing
  // about whether a microphone is attached to it, because those come apart --
  // a session can be established and held with no mic on it at all. Conflating
  // the two is what made `status === "connected"` mean "listening", which is
  // wrong the moment a connection exists before the user has asked to talk.
  const [transport, setTransport] = useState("idle"); // idle | connecting | ready | error
  // Whether a microphone is attached to the session. Combined with mode and
  // holding by isListening(), which is what should drive any "we can hear you"
  // affordance.
  const [micAttached, setMicAttached] = useState(false);
  // Observed, not inferred: both halves come from event pairs the server
  // sends. Fed to rimState() to pick which palette the rim wears.
  const [activity, setActivity] = useState({ userSpeaking: false, agentBusy: false });
  const [transcript, setTranscript] = useState([]);
  const [pendingAction, setPendingActionState] = useState(null); // { name, description, args }
  const [error, setError] = useState(null);
  const [mode, setModeState] = useState("continuous"); // continuous | ptt | ptnt
  const [holding, setHolding] = useState(false);

  const sessionRef = useRef(null);
  // A minted key waiting to be redeemed. Not a session and not a connection:
  // no audio, no cost, nothing open. Just a credential with ~10 minutes on it.
  const mintedRef = useRef(null);
  const warmingRef = useRef(null);
  // A mint in flight, so concurrent callers share one rather than each starting
  // their own. See ensureMinted.
  const mintingRef = useRef(null);
  /**
   * How many times in a row an action has failed the SAME way, so a doomed
   * call can be stopped rather than retried forever.
   *
   * A model that gets a validation error will try to fix it, which is right --
   * once the error says what is wrong (see the tRPC zodError surfacing). But if
   * the same action keeps failing the same way, more attempts will not help:
   * observed live, an update failed 18 times because its manifest carried no
   * body fields and no attempt could have been right. After a few, the widget
   * says stop and report, which is what a person would do.
   */
  const repeatFailRef = useRef({ key: null, count: 0 });
  // Created once. Does nothing unless BOTH this flag and the relay's VOICE_LOG
  // are on -- the relay says so in its mint response and the logger obeys.
  const loggerRef = useRef(null);
  if (logToRelay && !loggerRef.current) loggerRef.current = createRelayLogger({ relayUrl });
  const pendingRef = useRef(null); // mirrors pendingAction for use inside the tool-call closure
  // Set when the model hangs up, cleared the moment anyone starts talking again.
  const idleCloseRef = useRef(null);
  // The hang-up handler, reached through a ref for the same reason the
  // callback props are: warm() builds a session before standDown exists, and
  // that session is the one start() goes on to adopt.
  const hangUpRef = useRef(null);

  // Fallback nav for hosts that don't pass one: updates the URL and fires
  // popstate, which routers that listen to history will pick up. Hosts
  // with a real router should pass `navigate` so SPA nav works properly.
  const navigate = useCallback(
    (path) => {
      if (navigateProp) return navigateProp(path);
      window.history.pushState({}, "", path);
      window.dispatchEvent(new PopStateEvent("popstate"));
    },
    [navigateProp],
  );

  // Callback props are read through refs so their identity churning on
  // every parent render never forces us to re-create executeTool/effects.
  const callbacksRef = useRef({});
  callbacksRef.current = { onToolCall, onTranscript, onPendingAction, onModeChange, onTransportChange, onAfterAction, onHangUp };

  const setPendingAction = (value) => {
    pendingRef.current = value ? { action: value.action, batch: value.batch } : null;
    const publicValue = value
      ? {
          name: value.action.name,
          description: value.action.description,
          args: value.batch[0],
          // How many things this one confirmation covers. A destructive batch
          // is approved once for the whole set -- seven separate "are you
          // sure?" rounds is what this exists to stop.
          count: value.batch.length,
        }
      : null;
    setPendingActionState(publicValue);
    callbacksRef.current.onPendingAction?.(publicValue);
  };

  // No manifest fetch. It arrives as a prop from the app that owns it, so
  // there is nothing to download, nothing to go stale, and no way for this to
  // be describing an app other than the one it is running inside.
  useEffect(() => {
    if (!manifest) {
      setError("VoiceProvider needs a `manifest` prop: import your app's .voice/manifest.json and pass it in.");
    }
  }, [manifest]);

  // The realtime relay's model options: asked only when a realtime provider is
  // on offer (another provider has no relay to answer).
  const offersRealtime = providerList.some((p) => p.id === "openai-realtime");
  useEffect(() => {
    if (!offersRealtime) return;
    fetch(`${relayUrl}/voice/options`)
      .then((r) => r.json())
      .then((o) => {
        setOptions(o);
        setModelState((current) => current ?? o.defaults?.model ?? null);
      })
      .catch(() => {
        // Non-fatal: without options the settings UI simply offers nothing to
        // change, and the relay's own defaults still apply.
      });
  }, [relayUrl, offersRealtime]);

  const findQuery = (name) => manifest.queries.find((q) => q.name === name);
  const findAction = (name) => manifest.actions.find((a) => a.name === name);

  /**
   * One path for every operation, whatever wire shape it uses.
   *
   * The manifest says which transport an operation speaks, and how a request
   * is built and a reply read lives in transports.js. Sending a tRPC procedure
   * a plain REST body gets a 400 that explains nothing, so this is not a
   * detail the caller can be left to get right.
   */
  const perform = async (operation, args) => {
    // A flow is an action that happens in the page rather than over HTTP.
    // Same shape, same tool, different execution -- which is why the model
    // never has to know a dialog is involved.
    // `page` comes from the manifest entry, so a flow declared for one screen
    // never starts on another. Absent means the flow is not tied to a page.
    if (operation.transport === "dom") return dom.runFlow(operation.steps, args, { page: operation.page });

    const transport = transportFor(operation);
    const { method, url, body } = transport.request({ operation, args });
    const response = await apiFetch(method, url, body);
    return transport.read(response.data, response);
  };

  const runQuery = (query, args) => perform(query, args);

  const runAction = async (action, args) => perform(action, args);

  /**
   * Make the app SHOW the change. We wrote to the API out of band, so the app's
   * client-side cache (React Query, SWR, ...) does not know, and the UI can sit
   * stale until a refetch -- a create that "only shows after a refresh".
   *
   * A host that wired `onAfterAction` knows its cache and invalidates precisely,
   * so we defer to it, handing it the action name and result so it can be
   * surgical (`onAfterAction({ name }) => name.startsWith("availability") && ...`).
   * Absent that hook, we nudge the app's own data layer: React Query and SWR
   * refetch stale queries on window focus by default, so a synthetic
   * focus/visibilitychange updates the UI on most apps with no dev cooperation,
   * and is an inert no-op where they do not.
   *
   * Called once per OPERATION -- runBatch is the single write choke point -- not
   * once per batched item.
   */
  const refreshHost = (ctx) => {
    const onAfter = callbacksRef.current.onAfterAction;
    if (onAfter) return void onAfter(ctx);
    if (typeof window === "undefined") return;
    try {
      document.dispatchEvent(new Event("visibilitychange"));
      window.dispatchEvent(new Event("focus"));
    } catch {
      /* SSR or a restricted context; nothing to nudge */
    }
  };

  /**
   * Runs an action once per entry. Sequential rather than parallel: these are
   * writes against the host's API, and a batch of creates that races itself
   * can land in an order the user did not ask for.
   *
   * A single-item batch returns the bare result, so the model sees exactly
   * what it saw before batching existed.
   */
  const runBatch = async (action, batch) => {
    const results = [];
    for (const one of batch) {
      try {
        results.push(await runAction(action, one));
      } catch (err) {
        results.push({ error: String(err.message || err) });
      }
    }
    const result = batch.length === 1 ? results[0] : { count: results.length, results };

    // At least one write landed: make the app reflect it. Once, after the whole
    // batch, not per item -- see refreshHost.
    if (results.some((r) => r && !r.error)) refreshHost({ name: action.name, count: batch.length, result });

    // Stop a call that will not succeed by retrying. Keyed on the action and
    // the error text, so a DIFFERENT error (a field corrected, the next
    // revealed) resets the count -- that is progress, not a loop.
    const failure = result?.error ?? results.find((r) => r?.error)?.error;
    if (!failure) {
      repeatFailRef.current = { key: null, count: 0 };
      return result;
    }
    const { retryable } = classifyError(failure);
    const key = `${action.name}:${failure}`;
    const rf = repeatFailRef.current;
    rf.count = key === rf.key ? rf.count + 1 : 1;
    rf.key = key;

    // A validation or fatal error will reject the same call every time. Say so
    // on the FIRST failure -- retrying the identical arguments cannot help, and
    // each retry re-sends the whole conversation and pushes the rate limit
    // deeper. A transient error (a rate limit) gets the benefit of the doubt: it
    // is only cut off if it repeats, since a wait genuinely fixes it. The budget
    // also tightens for a low-confidence action: an unknown shape is a guess a
    // retry only re-sends.
    const limit = retryBudget(action, { retryable });
    if (rf.count >= limit) {
      repeatFailRef.current = { key: null, count: 0 };
      // For an operation whose API path we do not trust, the advice IS the
      // steer to the screen. Otherwise the older advice stands.
      const advice =
        screenSteer(action) ??
        (retryable
          ? `This call has failed ${rf.count} times the same way. Stop and tell the user what failed.`
          : `The arguments are wrong and this exact call will keep failing. Do NOT retry it. Either send a substantially different shape, or use the DOM tools (dom_snapshot then dom_click/dom_type) to do it on the page. If neither is possible, tell the user what failed.`);
      return { error: `${failure}`, stop: advice };
    }
    return result;
  };

  /**
   * Hand an open-ended instruction to the app's OWN agent (DELEGATION.md). We do
   * not execute it -- only the app's agent knows how. For the `ui` transport we
   * drive its real chat, so the turn shows in the app's panel and its hooks fire;
   * we read back the reply so the model can narrate it.
   */
  const runDelegate = async (agent, instruction) => {
    if (agent.transport === "api") {
      return { error: `The "${agent.id}" agent uses the api transport, which this build does not wire yet. See DELEGATION.md.` };
    }
    if (typeof window === "undefined" || !agent.ui) {
      return { error: `The "${agent.id}" agent has no ui binding to drive.` };
    }
    return await dom.delegate(agent.ui, instruction);
  };

  const executeTool = useCallback(
    async (name, args) => {
      if (!manifest) return { error: "Manifest not loaded yet" };

      if (name === "navigate") {
        const currentPath = typeof location !== "undefined" ? location.pathname : "";
        const plan = planNavigation(args, manifest.routes, currentPath);
        if (plan.error) {
          // A real message rather than a React Router stack trace. The model
          // retried an identical malformed call three times against the old
          // error, which told it nothing about what was wrong.
          return {
            error: `Could not find a route in ${JSON.stringify(args)}. Pass { "path": "/settings" }.`,
            knownRoutes: manifest.routes.map((r) => r.path),
          };
        }
        if (plan.missing) {
          // A parameterised route we could not fill from the args or the current
          // url. Do NOT navigate a pattern with a hole -- the router lands on
          // not-found, which reads as "went somewhere random". Tell the model
          // exactly what to resolve; a list query usually returns the id, or it
          // can ask the user.
          return {
            error: `Cannot navigate to ${plan.pattern}: no value for ${plan.missing.join(", ")}. Resolve ${plan.missing.length > 1 ? "them" : "it"} (a list query usually returns the id) or ask the user, then pass it -- e.g. { "path": "${plan.pattern}", "${plan.missing[0]}": "..." }. If the value cannot be found, do it on the SCREEN instead: click the matching link, then dom_snapshot.`,
            needs: plan.missing,
          };
        }
        const path = plan.path;
        navigate(path);

        /**
         * Wait for the destination to exist, then report where we actually
         * ARE -- both of which this used to skip.
         *
         * It returned the moment `navigate` was called, echoing the path it
         * was asked for. Two separate lies. The page had not rendered, so the
         * next snapshot described the app shell and the model concluded the
         * screen did not have what it came for. And cal.diy bounces any admin
         * settings route to the profile page, so the model was told it was
         * somewhere it had never been.
         *
         * `readyWhen` comes off the route in the manifest: a page saying what
         * "ready" looks like. Declared, we wait for that exact thing and can
         * afford to be patient. Undeclared, we guess briefly and say so.
         */
        // By PATTERN, not by string: the manifest says /availability/:schedule
        // and we are going to /availability/50, so an exact match finds
        // nothing and every parameterised page silently loses its trigger.
        const route = (manifest.routes ?? []).find((r) => r.path === path || dom.onPage(r.path, path));
        const settled = await dom.waitForPage({ readyWhen: route?.readyWhen });
        const landed = typeof location !== "undefined" ? location.pathname : path;

        // L0 live context: ground the model in where it ACTUALLY landed (which,
        // for a bounced route, is not where it aimed) -- the matched route's own
        // description, the params now in the url so the next call reuses them,
        // and the page's heading. Cheap, and it rides this tool result, so there
        // is no separate item to evict. Matched against `landed`, not `path`.
        const here = (manifest.routes ?? []).find((r) => r.path === landed || dom.onPage(r.path, landed));
        const params = here ? matchPattern(here.path, landed) : null;
        const { title, heading } = dom.pageContext();
        const context = {
          ...(here?.description ? { page: here.description } : {}),
          ...(here && here.path !== landed ? { route: here.path } : {}),
          ...(params && Object.keys(params).length ? { params } : {}),
          ...(heading ? { heading } : title ? { heading: title } : {}),
        };

        return {
          status: "navigated",
          // Where we ended up, which is not always where we aimed.
          path: landed,
          ...(Object.keys(context).length ? { context } : {}),
          ...(landed !== path ? { asked: path, note: "the app sent us somewhere else" } : {}),
          // Only when it is bad news. A page that came up cleanly says nothing.
          // Three outcomes, not two. A declared trigger that fired is the only
          // one that means "ready". Everything else is a page we stopped
          // waiting on, and the difference matters: concluding something is
          // absent from a page nobody confirmed had rendered is exactly how a
          // session walked away from the screen it needed.
          ...(settled.ready
            ? {}
            : {
                readiness: settled.assumed ? "assumed" : "gave up waiting",
                hint: settled.assumed
                  ? (settled.settledWithout
                      ? `The page stopped changing without ever showing ${JSON.stringify(settled.settledWithout)}, which usually means there is none of it to show -- an empty list, a schedule with no days. Snapshot and work with what is there.`
                      : "This route declares no readiness signal, so the page may still be filling in. If what you expect is missing, snapshot again before concluding it is absent.")
                  : `The page never showed ${JSON.stringify(settled.missing ?? [])}. Snapshot to see what it did render.`,
              }),
          ...(path === args.path ? {} : { interpretedFrom: args }),
        };
      }

      // Signals to the transport layer, already acted on before they got here;
      // surfaced so onToolCall can log what the model decided and why.
      if (name === "answer_aloud") {
        return { acknowledged: true, because: args.because };
      }
      // Deliberately not the hang-up itself. The microphone is released when
      // the goodbye finishes, several seconds after this returns, and saying
      // so here would be a lie the model then reads aloud.
      if (name === "end_session") {
        return { acknowledged: true, because: args.because };
      }

      // A ring answers the question it was drawn for and nothing after it.
      // Cleared before any tool that is not itself a highlight, rather than on
      // a timer: whatever happens next is a new answer, and a ring left over
      // from the previous one points confidently at something nobody asked
      // about. dom_snapshot is exempt because looking is how the model finds
      // what to point at, and clearing there would erase the ring it is about
      // to redraw.
      if (name !== "dom_highlight" && name !== "dom_snapshot") dom.clearHighlight();

      if (name === "dom_snapshot") {
        return { elements: dom.snapshot() };
      }
      // Lists, like every action_* tool. A single id is a list of one, and
      // that spelling is still accepted: an older session prompt is in flight
      // for as long as a session lives, and a tool that rejects the shape the
      // model was taught fails the turn rather than the argument.
      if (name === "dom_click") {
        const ids = args.elementIds ?? [args.elementId];
        return dom.runSteps(ids.map((elementId) => ({ elementId })));
      }
      if (name === "dom_type") {
        const items = args.items ?? [{ elementId: args.elementId, text: args.text }];
        return dom.runSteps(items);
      }
      if (name === "dom_highlight") {
        return dom.highlight(args.elementId);
      }

      if (name === "confirm_pending_action") {
        const pending = pendingRef.current;
        if (!pending) return { error: "Nothing is pending confirmation" };
        setPendingAction(null);
        return await runBatch(pending.action, pending.batch);
      }
      if (name === "cancel_pending_action") {
        setPendingAction(null);
        return { status: "cancelled" };
      }

      // The dispatcher. Operations are called by NAME rather than each being
      // its own typed tool, so the tool surface stays small enough to fit the
      // prompt whatever the app's size. See catalog.js and the relay's.
      if (name === "expand") {
        const found = expandTopic(manifest, args.topic);
        return found ?? { error: `No topic "${args.topic}". Expand one from the catalog or an expand result.` };
      }
      if (name === "run_query") {
        const query = findQuery(args.name);
        if (!query) return { error: `Unknown query "${args.name}". Names come from the catalog or expand().` };
        return await runQuery(query, args.args ?? {});
      }
      if (name === "run_action") {
        const action = findAction(args.name);
        if (!action) return { error: `Unknown action "${args.name}". Names come from the catalog or expand().` };

        // `items` is the list of changes. If the model put the fields at the
        // top level instead (everything except `name`), treat that as a list of
        // one -- a model that ignores the schema this way is not hypothetical.
        const batch = Array.isArray(args.items) && args.items.length > 0
          ? args.items
          : (() => {
              const { name: _n, items: _i, ...rest } = args;
              return Object.keys(rest).length ? [rest] : [];
            })();
        if (!batch.length) return { error: `run_action "${args.name}" needs items: a list of the changes to make.` };

        if (action.requiresConfirmation) {
          setPendingAction({ action, batch });
          return {
            status: "needs_confirmation",
            staged: batch.length,
            // Deliberately does NOT echo the batch back: the model just sent
            // it, and repeating eleven objects costs tokens to tell it what it
            // already knows. It also phrases the question better than we can,
            // because it has the titles and we only have ids -- so this says
            // when to ask, not what to say.
            message:
              `Staged, NOT executed. Ask the user once to confirm ` +
              `${batch.length === 1 ? "this" : `all ${batch.length}`}, naming what will change. ` +
              `Then call confirm_pending_action (no arguments). Do not call ${name} again.`,
          };
        }
        return await runBatch(action, batch);
      }

      // Delegate to one of the app's registered agents (DELEGATION.md). The
      // model routes here by the agent's description; we drive its chat.
      if (name === "ask") {
        const agent = (manifest.agents ?? []).find((a) => a.id === args.agent);
        if (!agent) {
          return {
            error: `Unknown agent "${args.agent}". Agents come from the catalog.`,
            knownAgents: (manifest.agents ?? []).map((a) => a.id),
          };
        }
        const instruction = typeof args.instruction === "string" ? args.instruction.trim() : "";
        if (!instruction) {
          return { error: `ask "${args.agent}" needs an instruction: what to tell the agent, in plain language.` };
        }
        return await runDelegate(agent, instruction);
      }

      // A safety net that teaches, not just rejects. A model given a catalog
      // of operation names sometimes calls a NAME as if it were its own tool
      // (`availabilityScheduleGet(...)`), or invents a short dispatcher name
      // (`query(...)`). The widget holds the manifest, so it can tell what was
      // meant and answer with the exact call to make -- which turns a dead turn
      // into a corrected one. Observed live: without this the model thrashed
      // through five wrong shapes and gave up.
      const asQuery = findQuery(name);
      if (asQuery) {
        return { error: `"${name}" is an operation name, not a tool. Call it as run_query({ "name": "${name}", "args": {} }).` };
      }
      const asAction = findAction(name);
      if (asAction) {
        return { error: `"${name}" is an operation name, not a tool. Call it as run_action({ "name": "${name}", "items": [ {} ] }).` };
      }
      if (name === "query" || name === "action") {
        return { error: `There is no "${name}" tool. Use run_query({ name, args }) to read or run_action({ name, items }) to change.` };
      }
      return { error: `Unrecognized tool: ${name}. Read with run_query, change with run_action, and see what exists with expand.` };
    },
    [manifest, navigate],
  );

  // `overrides` exists because a reconnect triggered by changing model or
  // language has to use the NEW value, and the state update has not landed in
  // this closure yet. Reading it from state here would reconnect with exactly
  // the setting the user just changed away from -- silently, and only on the
  // reconnect path, which is the kind of bug that survives a long time.
  /**
   * Keep a usable key in hand. Called on a timer AND before every use, because
   * the timer cannot be trusted: a backgrounded tab has its intervals throttled
   * to roughly one a minute, so a 9-minute refresh may simply not fire. The
   * check at the point of use is the guarantee; the timer is an optimisation.
   */
  const ensureMinted = useCallback(async (overrides = {}) => {
    const { provider } = activeProviderRef.current;
    // No credential to pre-acquire (a per-turn broker) means no mint to call.
    if (typeof provider.mint !== "function") return null;
    const wanted = {
      model: overrides.model ?? model ?? null,
      language: overrides.language ?? language ?? null,
    };
    if (isUsable(mintedRef.current, wanted)) return mintedRef.current;

    /**
     * One mint at a time. The check above reads a ref and the mint is a
     * network round trip, so two callers arriving inside that window both saw
     * "no key" and both minted.
     *
     * That is not hypothetical: the warm effect depends on this callback,
     * which depends on `model`, which is null until the relay's options
     * arrive and then becomes the default -- so the effect fires twice within
     * a few hundred milliseconds of mount, and StrictMode's double-mount adds
     * more. Real sessions showed three and four mints inside 300ms, each one
     * a session record on the relay and a log file nobody ever used.
     */
    if (mintingRef.current) return mintingRef.current;
    mintingRef.current = (async () => {
      try {
        mintedRef.current = await provider.mint({ relayUrl, ...wanted, manifest, minted: mintedRef.current });
        return mintedRef.current;
      } catch {
        // Warming must never surface an error: nobody asked for this yet, and
        // the Talk button will mint again and report properly if it still fails.
        mintedRef.current = null;
        return null;
      } finally {
        mintingRef.current = null;
      }
    })();
    return mintingRef.current;
  }, [relayUrl, model, language, manifest]);

  /**
   * Connect with no microphone attached. Safe to call more than once and safe
   * to call when nobody has asked to talk: `micAttached` stays false, so
   * isListening() stays false, so the rim stays dark. That separation is the
   * whole reason the transport/listening split exists.
   */
  const warm = useCallback(async () => {
    const { provider } = activeProviderRef.current;
    // `!provider.capabilities.warm` kept last so the substring the warm tests
    // pin (`warmup === "off" || sessionRef.current`) stays intact: a provider
    // with nothing to pre-open (a per-turn broker) is never warmed.
    if (warmup === "off" || sessionRef.current || warmingRef.current || !provider.capabilities.warm) return;
    warmingRef.current = (async () => {
      setTransport("connecting");
      try {
        const session = await provider.connect({
          callbacks: {
            onToolCall: async (name, args) => {
              const result = await executeTool(name, args);
              callbacksRef.current.onToolCall?.(name, args, result);
              return result;
            },
            onStatus: (st) => {
              const next = st === "closed" ? "idle" : st;
              setTransport(next);
              if (next === "idle") setMicAttached(false);
              callbacksRef.current.onTransportChange?.(next);
            },
            onTranscript: (turn) => {
              setTranscript((t) => [...t, turn]);
              callbacksRef.current.onTranscript?.(turn);
            },
            onEvent: (event) => loggerRef.current?.record(event),
            onActivity: setActivity,
            onHangUp: (info) => hangUpRef.current?.(info),
          },
          initialMode: mode,
          relayUrl,
          model,
          language,
          manifest,
          toolCatalog: catalog,
          minted: await ensureMinted(),
          withMic: false,
        });
        sessionRef.current = session;
      } catch {
        setTransport("idle"); // silent: nobody asked for this
      } finally {
        warmingRef.current = null;
      }
    })();
    return warmingRef.current;
  }, [warmup, mode, relayUrl, model, language, catalog, ensureMinted, executeTool]);

  // "eager" mints on mount and keeps it fresh. A key is not a session: nothing
  // is open, nothing is billed, and if it expires unused it costs nothing.
  useEffect(() => {
    if (warmup !== "eager" && warmup !== "hover") return;
    ensureMinted();
    const id = setInterval(ensureMinted, 4 * 60_000);
    return () => clearInterval(id);
  }, [warmup, ensureMinted]);

  const start = async (overrides = {}) => {
    setError(null);
    // Whatever was scheduled by a hang-up, someone is talking again.
    clearTimeout(idleCloseRef.current);
    idleCloseRef.current = null;
    // Already warm: the only thing left is the microphone.
    await warmingRef.current;
    if (sessionRef.current) {
      try {
        await sessionRef.current.attachMic();
        setMicAttached(true);
      } catch (err) {
        setError(String(err.message || err));
        setTransport("error");
      }
      return;
    }
    setTransport("connecting");
    try {
      // `overrides.provider` lets a provider switch connect the NEW engine
      // before its state update has landed in this closure -- the same trick
      // the model/language reconnect uses for `overrides.model`.
      const { provider } = overrides.provider ?? activeProviderRef.current;
      const session = await provider.connect({
        callbacks: {
          onToolCall: async (name, args) => {
            const result = await executeTool(name, args);
            callbacksRef.current.onToolCall?.(name, args, result);
            return result;
          },
          onStatus: (s) => {
            const next = s === "closed" ? "idle" : s;
            setTransport(next);
            if (next === "idle") setMicAttached(false);
            callbacksRef.current.onTransportChange?.(next);
          },
          onTranscript: (turn) => {
            setTranscript((t) => [...t, turn]);
            callbacksRef.current.onTranscript?.(turn);
          },
          onEvent: (event) => loggerRef.current?.record(event),
          onActivity: setActivity,
          onHangUp: (info) => hangUpRef.current?.(info),
        },
        initialMode: mode,
        relayUrl,
        model: overrides.model ?? model,
        language: overrides.language ?? language,
        manifest,
        toolCatalog: catalog,
        minted: await ensureMinted(overrides),
      });
      sessionRef.current = session;
      // Today the mic is acquired as part of connecting, so this is true as soon
      // as the session exists. It is tracked separately so that stops being an
      // assumption the rest of the widget is built on.
      setMicAttached(true);
    } catch (err) {
      setError(String(err.message || err));
      setTransport("error");
    }
  };

  const stop = () => {
    clearTimeout(idleCloseRef.current);
    idleCloseRef.current = null;
    loggerRef.current?.stop();
    sessionRef.current?.stop();
    sessionRef.current = null;
    setTransport("idle");
    setMicAttached(false);
    setActivity({ userSpeaking: false, agentBusy: false });
    setHolding(false);
  };

  /**
   * The model hung up, because the user dismissed it.
   *
   * Two steps at two speeds, which is the whole design. The microphone goes
   * NOW: that is what the user asked for, it is the part they can verify from
   * their own OS indicator, and every second of delay is a second of a live
   * mic nobody wants. The connection goes later, or not at all if they come
   * back, because closing it throws away a session-scoped prompt cache and
   * makes "actually, one more thing" cost a full reconnect.
   *
   * A staged destructive action does not survive this. Saying "that's all"
   * with a delete waiting to be confirmed has to mean the delete is off --
   * otherwise it sits there and the next "yes", in some later conversation,
   * executes something nobody is thinking about any more.
   */
  const standDown = async ({ because } = {}) => {
    setPendingAction(null);
    setHolding(false);
    await sessionRef.current?.releaseMic();
    setMicAttached(false);
    setActivity({ userSpeaking: false, agentBusy: false });
    callbacksRef.current.onHangUp?.({ because });

    clearTimeout(idleCloseRef.current);
    idleCloseRef.current = setTimeout(() => {
      // Only if nobody came back. hasMic() is the session's own answer rather
      // than this closure's stale copy of micAttached.
      if (sessionRef.current && !sessionRef.current.hasMic()) stop();
    }, idleCloseMs);
  };
  hangUpRef.current = standDown;

  const sendText = (text) => {
    setTranscript((t) => [...t, { role: "user", text }]);
    callbacksRef.current.onTranscript?.({ role: "user", text });
    sessionRef.current?.sendTextTurn(text);
  };

  const confirmManually = () => executeTool("confirm_pending_action", {});
  const cancelManually = () => executeTool("cancel_pending_action", {});

  /**
   * Model and language, unlike mode, CANNOT be changed on a live session --
   * both are fixed when the session is minted. So changing one while connected
   * means tearing the session down and building a new one, which loses the
   * conversation history. Doing it silently would be worse than the reconnect:
   * the user would keep talking to a session configured the way it was before
   * they changed it.
   */
  const reconfigure = (apply, overrides) => {
    const wasLive = !!sessionRef.current;
    if (wasLive) stop();
    apply();
    if (wasLive) start(overrides);
  };

  const setModel = (next) => reconfigure(() => setModelState(next), { model: next });
  const setLanguage = (next) => reconfigure(() => setLanguageState(next), { language: next });

  /**
   * Switch the whole pipeline -- OpenAI Realtime to another realtime API. Unlike
   * model/language this is a different IMPLEMENTATION, not a parameter, so it is
   * always a reconnect (a live session is torn down). A minted credential is
   * provider-specific, so it is dropped: an ephemeral key for Realtime means
   * nothing to another provider. And a provider that cannot push-to-talk cannot be
   * left in ptt/ptnt, so the mode falls back to continuous.
   */
  const setProvider = (id) => {
    const next = providerList.find((p) => p.id === id);
    if (!next || next.id === activeProvider.id) return;
    mintedRef.current = null;
    if (!next.capabilities.pushToTalk && mode !== "continuous") setModeState("continuous");
    reconfigure(() => setProviderIdState(id), { provider: next });
  };

  // Switching modes never reconnects -- same session, same history, same
  // instructions. It just changes who decides when a turn ends (VAD vs. a
  // held button) and what the mic's resting state is.
  const setMode = (newMode) => {
    const session = sessionRef.current;
    if (session) {
      if (newMode === "ptt") {
        session.setTurnDetection(false);
        session.setMicEnabled(false); // resting state: muted, hold to talk
      } else {
        session.setTurnDetection(true);
        session.setMicEnabled(true); // resting state: live (continuous or ptnt)
      }
    }
    setHolding(false);
    setModeState(newMode);
    callbacksRef.current.onModeChange?.(newMode);
  };

  const holdStart = () => {
    const session = sessionRef.current;
    if (!session || mode === "continuous") return;
    setHolding(true);
    if (mode === "ptt") {
      session.cancelResponse(); // barge-in: stop the model if it's still talking
      session.clearInputBuffer();
      session.setMicEnabled(true);
    } else if (mode === "ptnt") {
      session.setMicEnabled(false);
    }
  };

  const holdEnd = () => {
    const session = sessionRef.current;
    if (!session || mode === "continuous" || !holding) return;
    setHolding(false);
    if (mode === "ptt") {
      session.setMicEnabled(false);
      session.commitAndRespond();
    } else if (mode === "ptnt") {
      session.setMicEnabled(true);
    }
  };

  // Ctrl+Space as a keyboard hold, mirroring the hold button. Subscribes
  // once and calls through refs so it never sees a stale `mode`/`holding`
  // closure -- holdStart/holdEnd already no-op when disconnected or in
  // continuous mode, so this listener can just stay attached globally.
  const holdStartRef = useRef(holdStart);
  const holdEndRef = useRef(holdEnd);
  holdStartRef.current = holdStart;
  holdEndRef.current = holdEnd;

  // A pending close outlives the component otherwise, and fires stop() against
  // a session that unmounting already tore down.
  useEffect(() => () => clearTimeout(idleCloseRef.current), []);

  useEffect(() => {
    function isEditableTarget(el) {
      return !!el && (el.tagName === "INPUT" || el.tagName === "TEXTAREA" || el.isContentEditable);
    }
    function onKeyDown(e) {
      if (e.code !== "Space" || !e.ctrlKey || e.repeat) return;
      if (isEditableTarget(document.activeElement)) return;
      e.preventDefault();
      holdStartRef.current();
    }
    function onKeyUp(e) {
      // Releasing either key ends the hold, not just Space -- matches how
      // a physical push-to-talk button behaves if you let go early.
      if (e.code !== "Space" && !e.code.startsWith("Control")) return;
      holdEndRef.current();
    }
    window.addEventListener("keydown", onKeyDown);
    window.addEventListener("keyup", onKeyUp);
    return () => {
      window.removeEventListener("keydown", onKeyDown);
      window.removeEventListener("keyup", onKeyUp);
    };
  }, []);

  return (
    <InterpreterContext.Provider
      value={{
        transport,
        micAttached,
        ...activity,
        transcript,
        pendingAction,
        error,
        manifest,
        mode,
        holding,
        options,
        model,
        language,
        setModel,
        setLanguage,
        // The engines on offer and which is live, for an engine picker. A plain
        // single-provider setup still gets a one-entry list.
        providers: providerList.map(({ id, label, capabilities }) => ({ id, label, capabilities })),
        providerId: activeProvider.id,
        setProvider,
        // What the LIVE provider can do, so the UI can hide controls it does not
        // support (push-to-talk, barge-in, text input) instead of showing dead ones.
        capabilities,
        rimMode,
        setRimMode,
        rimModes: RIM_MODES,
        rimPalettes: rimMode === "single" ? fixedPalettes() : PALETTES,
        start,
        stop,
        sendText,
        confirmManually,
        cancelManually,
        setMode,
        warm,
        warmup,
        holdStart,
        holdEnd,
      }}
    >
      {/* One overlay for all widget chrome, mounted here so consumers never
          place it and so the rim and the panel end up in the same shadow
          root. Two of them could not agree an order in the top layer without
          fighting each other for it -- see LAYERS in ScreenOverlay.jsx. */}
      <OverlayProvider>{children}</OverlayProvider>
    </InterpreterContext.Provider>
  );
}

/**
 * The public headless API. Everything the built-in UI components use is
 * available here too -- there's nothing they can do that a custom UI
 * built on this hook can't.
 */
export function useInterpreter() {
  const ctx = useContext(InterpreterContext);
  if (!ctx) throw new Error("useInterpreter must be used inside a VoiceProvider");
  return ctx;
}
